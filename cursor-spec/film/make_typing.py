# Writes deterministic keystroke times into cues.js (shared by picture and sound).
import json, random, re
TEXT = {
  'H1': ("WHAT IF YOUR IDEAS", 0.85, 1.95),
  'H2': ("MOVED FASTER?", 2.45, 3.20),
  'T1': ('export function useMetrics(range: "7d" | "30d") {', 10.35, 11.75),
  'T2': ('export const compact = (n: number) =>', 13.85, 14.85),
  'TP': ('Build a clean analytics dashboard with charts and responsive cards.', 17.30, 18.60),
}
r = random.Random(7)
out = {}
for k, (s, a, b) in TEXT.items():
    w = [(1.6 if ch in ' .,(){}' else 1.0) * (0.65 + 0.7 * r.random()) for ch in s]
    tot = sum(w); t = a; ts = []
    for x in w:
        ts.append(round(t, 3)); t += (b - a) * x / tot
    out[k] = ts
src = open('cues.js').read()
src = re.sub(r'\n  // typing \(generated\)[\s\S]*?(?=\n};)', '', src)
add = '\n  // typing (generated by make_typing.py): time of each keystroke\n' + ',\n'.join(f'  {k}: {json.dumps(v)}' for k, v in out.items())
src = src.replace('\n};', ',' + add + '\n};') if not src.rstrip().endswith(',\n};') else src
open('cues.js', 'w').write(src)
print({k: len(v) for k, v in out.items()})
